import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { fixtureServer, A } from './fixture-server.ts';
import { unifiedFixture } from './unified-fixture.ts';
const app = await fixtureServer({phaseDelayMs:0,publicExploration:true,explorationCooldownMs:0,explorationTransport:unifiedFixture().transport});
const browser = await chromium.launch();
try {
 const page=await browser.newPage();
 await page.goto(app.url);
 let release!:()=>void;
 const gate=new Promise<void>(r=>release=r);
 let arrived!:()=>void;
 const viewRequest=new Promise<void>(r=>arrived=r);
 await page.route('**/api/view/**',async route=>{arrived();await gate;await route.continue().catch(()=>{});});
 await page.fill('#repo-input',A);await page.click('#submit');
 await page.locator('#analysis:not([hidden])').waitFor();
 await viewRequest;
 await page.goBack();
 assert.equal(await page.locator('#analysis').isVisible(),false,'Returning home immediately dismisses the analysis surface');
 release();await page.waitForTimeout(500);
 assert.equal(await page.locator('#landing').isVisible(),true,'Late repository response cannot replace homepage');
 assert.equal(await page.locator('#explorer').isVisible(),false,'Late graph response stays cancelled');
 await page.unroute('**/api/view/**');
 await page.fill('#repo-input',A);await page.click('#submit');
 await page.locator('#canvas .node-hit').first().waitFor();
 await page.evaluate(()=>{(window as Window & {__navigationSentinel?:boolean}).__navigationSentinel=true;});
 await page.locator('.brand').click();
 await page.locator('#landing:not([hidden])').waitFor();
 assert.equal(await page.evaluate(()=>(window as Window & {__navigationSentinel?:boolean}).__navigationSentinel),true,'Home navigation preserves the already loaded application');
 assert.equal(await page.locator('#rail-toggle').isVisible(),false,'Context is shown only in the explorer');
 await page.goBack();
 await page.locator('#workspace-history').click();
 await page.locator('#git-history').waitFor();
 await page.locator('.brand').click();
 assert.equal(await page.locator('#git-history').count(),0,'Leaving History for home removes the reader');
 assert.equal(await page.evaluate(()=>document.body.classList.contains('history-open')),false,'Home clears History presentation state');
 await page.goBack();
 assert.equal(await page.locator('#stage').evaluate(n=>(n as HTMLElement).inert),false,'Returning graph remains interactive');
 const quota=await browser.newPage();
 await quota.route('**/api/explore',route=>route.fulfill({status:429,json:{error:'Anonymous quota exhausted; resets 2026-10-17T07:47:39.915Z'}}));
 await quota.goto(app.url+'/'+A);await quota.locator('#workspace-history').click();
 await quota.locator('.history-load-title').filter({hasText:'Anonymous limit reached'}).waitFor();
 assert.equal(await quota.locator('#history-retry').count(),0,'A quota refusal does not encourage futile retries');
 assert.doesNotMatch(await quota.locator('.history-load-message').innerText(),/T07:47/,'Reset date is formatted for reading');
 await quota.locator('.history-load button').click();
 assert.equal(await quota.locator('#git-history').count(),0,'Quota state returns to usable graph');
 await quota.close();
 const phone=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
 await phone.goto(app.url+'/'+A);await phone.locator('#workspace-history').waitFor();
 await phone.locator('[data-mobile-view=relations]').click();
 await phone.locator('#mobile-relations details').evaluateAll(ns=>ns.forEach(n=>(n as HTMLDetailsElement).open=true));
 await phone.locator('.mobile-relation-evidence').first().click();await phone.evaluate(()=>document.fonts.ready);
 const labels=phone.locator('.d-data dt').filter({hasText:'manifest_path'});
 assert.ok(await labels.count()>0,'Manifest evidence is displayed on phone');
 assert.equal(await labels.evaluateAll(ns=>ns.every(n=>n.getBoundingClientRect().height<=parseFloat(getComputedStyle(n).lineHeight)+1)),true,'Manifest field label stays intact at 390px');
 await phone.close();
 console.log('PASS immediate home, cancelled stale response, no document reload, contextual navigation');
}finally{await browser.close();await app.cleanup();}
